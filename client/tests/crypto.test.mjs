import {test} from 'node:test';
import assert from 'node:assert/strict';
import sodium from 'libsodium-wrappers-sumo';
import {vaultCrypto} from '../src/crypto.mjs';
await sodium.ready;
const crypto=vaultCrypto(sodium);
const owner='11111111-1111-4111-8111-111111111111';
const vault='22222222-2222-4222-8222-222222222222';
const entry='33333333-3333-4333-8333-333333333333';
const record={title:'Example',username:'owner',password:'synthetic-only-secret',url:'https://example.test',notes:'<script>text only</script>'};
const password='synthetic test master password';
test('real Argon2id / XChaCha roundtrip, wrong password, ciphertext and context tampering',()=>{
  const {key,envelope}=crypto.create(password,owner,vault);
  const unlocked=crypto.unlock(password,owner,vault,envelope);
  assert.deepEqual(unlocked,key);
  const encrypted=crypto.encrypt(key,owner,vault,entry,1,record);
  const row={id:entry,revision:1,...encrypted};
  assert.deepEqual(crypto.decrypt(unlocked,owner,vault,row),record);
  assert.notEqual(crypto.encrypt(key,owner,vault,entry,1,record).nonce,encrypted.nonce);
  assert.throws(()=>crypto.unlock('wrong password',owner,vault,envelope));
  assert.throws(()=>crypto.unlock(password,entry,vault,envelope));
  assert.throws(()=>crypto.decrypt(key,owner,vault,{...row,revision:2}));
  assert.throws(()=>crypto.decrypt(key,owner,vault,{...row,id:owner}));
  assert.throws(()=>crypto.decrypt(key,entry,vault,row));
  assert.throws(()=>crypto.decrypt(key,owner,entry,row));
  const bytes=sodium.from_base64(encrypted.ciphertext,sodium.base64_variants.URLSAFE_NO_PADDING);bytes[0]^=1;
  assert.throws(()=>crypto.decrypt(key,owner,vault,{...row,ciphertext:sodium.to_base64(bytes,sodium.base64_variants.URLSAFE_NO_PADDING)}));
  assert.throws(()=>crypto.unlock(password,owner,vault,{...envelope,kdf:{...envelope.kdf,memory_kib:1073741824}}));
  assert.throws(()=>crypto.unlock(password,owner,vault,{...envelope,version:2}));
  sodium.memzero(unlocked);sodium.memzero(key);
});
